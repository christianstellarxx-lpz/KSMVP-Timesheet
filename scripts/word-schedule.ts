/**
 * Prints the Daily Word Guess play schedule — which curated answer lands on
 * which ET calendar day — so the list can be reviewed and trimmed before
 * launch, and the first few live days can be sanity-checked after deploy.
 *
 *   npm run word:schedule              # markdown table to stdout
 *   npm run word:schedule > docs/word-answer-schedule.md
 *
 * The order comes from the same fixed-seed shuffle the app uses, so what you
 * see here is exactly what players will get.
 */
import { DateTime } from "luxon";
import answers from "../src/lib/word/answers.json";
import allowed from "../src/lib/word/allowed.json";
import {
  ANSWER_SHUFFLE_SEED,
  WORD_EPOCH_DATE,
  seededShuffle,
} from "../src/lib/word/logic";

const playOrder = seededShuffle(answers as string[], ANSWER_SHUFFLE_SEED);
const epoch = DateTime.fromISO(WORD_EPOCH_DATE, { zone: "utc" });

const rows = playOrder.map((word, i) => {
  const day = epoch.plus({ days: i });
  return {
    index: i,
    date: day.toISODate()!,
    weekday: day.toFormat("ccc"),
    isWeekend: day.weekday > 5,
    word,
  };
});

const lastDay = rows[rows.length - 1];
const workdayCount = rows.filter((r) => !r.isWeekend).length;

const out: string[] = [];
out.push("# Daily Word Guess — answer schedule (review before launch)");
out.push("");
out.push(
  "Generated by `npm run word:schedule`. Edit `src/lib/word/answers.json` and re-run to see the effect.",
);
out.push("");
out.push(`- **Answers curated:** ${playOrder.length}`);
out.push(`- **Allowed guesses:** ${(allowed as string[]).length}`);
out.push(`- **First puzzle:** ${WORD_EPOCH_DATE} (\`WORD_EPOCH_DATE\`)`);
out.push(`- **List runs out / wraps:** ${lastDay.date}`);
out.push(
  `- **Playable (Mon–Fri) words in that span:** ${workdayCount} — weekend rows are marked and, in practice, never played (the game needs a Time In).`,
);
out.push("");
out.push(
  "> Removing a word shifts every later date by one. That's fine before launch; after launch it would change days people have already played, so trim now.",
);
out.push("");
out.push("| # | Date (ET) | Day | Word |");
out.push("|---:|---|---|---|");
for (const r of rows) {
  const word = r.isWeekend ? `_${r.word}_ (weekend)` : `**${r.word}**`;
  out.push(`| ${r.index + 1} | ${r.date} | ${r.weekday} | ${word} |`);
}
out.push("");

console.log(out.join("\n"));
